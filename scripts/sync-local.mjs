#!/usr/bin/env node
/**
 * sync-local.mjs — rebuild the bundle and refresh the local zappi-signer
 * command so the installed CLI always runs current code.
 *
 *   npm run sync:local
 *
 * What it does:
 *   1. Runs `npm run build:bin` — the exact build the release ships, so the
 *      local CLI always matches the artifact (tsc + esbuild bundle with the
 *      embedded keyring shim).
 *   2. Installs a thin `exec node <bundle>` wrapper at
 *      ~/.zappi-signer/bin/zappi-signer-<version>/<target>/zappi-signer,
 *      backing up any prior binary to <path>.orig (once).
 *   3. Point ~/.local/bin/zappi-signer at that wrapper.
 *
 * Never touches the vault, keychain, or trust pin. The wrapper runs the
 * bundle with system node — the configuration proven to work (the
 * Bun-compiled binary stalls the Spark gRPC transport; see docs/agent.md).
 * CI remains the authority for shipped release artifacts.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = `${process.platform}-${process.arch}`
const version = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8')).version
const bundlePath = join(pkgRoot, 'dist', 'bin', '.build', 'app.cjs')
const wrapperPath = join(homedir(), '.zappi-signer', 'bin', `zappi-signer-v${version}`, target, 'zappi-signer')
const symlinkPath = join(homedir(), '.local', 'bin', 'zappi-signer')

function run(command, args, opts = {}) {
  const result = spawnSync(command, args, { stdio: 'inherit', ...opts })
  if (result.status !== 0) {
    console.error(`[sync-local] ${command} ${args.join(' ')} failed`)
    process.exit(result.status ?? 1)
  }
}

run('npm', ['run', 'build:bin'], { cwd: pkgRoot })
if (!existsSync(bundlePath)) {
  console.error('[sync-local] bundle is missing after build:bin — build failed?')
  process.exit(1)
}

const wrapper = `#!/bin/sh
# Generated by packages/zappi-signer/scripts/sync-local.mjs — do not edit.
# Runs the current signer bundle under node (docs/agent.md explains why the
# Bun-compiled release binary is not used on this machine).
NODE="${process.execPath}"
if [ ! -x "$NODE" ]; then
  NODE="$(command -v node 2>/dev/null || true)"
fi
if [ -z "$NODE" ]; then
  for candidate in /opt/homebrew/bin/node /usr/local/bin/node; do
    if [ -x "$candidate" ]; then NODE="$candidate"; break; fi
  done
fi
if [ -z "$NODE" ]; then
  echo "zappi-signer: node is required on this machine for the dev wrapper." >&2
  echo "Either install node, or reinstall the standalone binary:" >&2
  echo "  curl -fsSL https://zappi.money/signer/install | sh" >&2
  exit 127
fi
exec "$NODE" ${bundlePath} "$@"
`
if (existsSync(wrapperPath)) {
  const current = readFileSync(wrapperPath, 'utf8')
  if (!current.includes('sync-local.mjs')) {
    const backup = `${wrapperPath}.orig`
    if (!existsSync(backup)) {
      writeFileSync(backup, current, { mode: 0o500 })
      console.log(`[sync-local] backed up previous binary to ${backup}`)
    }
  }
  rmSync(wrapperPath)
}
mkdirSync(dirname(wrapperPath), { recursive: true })
writeFileSync(wrapperPath, wrapper, { mode: 0o500 })
mkdirSync(dirname(symlinkPath), { recursive: true })
rmSync(symlinkPath, { force: true })
symlinkSync(wrapperPath, symlinkPath)

console.log(`[sync-local] zappi-signer v${version} (${target}) synced: ${symlinkPath} -> ${wrapperPath}`)
